
import os
import sqlite3
import secrets
from datetime import datetime, timedelta, timezone
from pathlib import Path

import jwt
from fastapi import APIRouter, HTTPException, Request, Response
from pydantic import BaseModel, EmailStr, Field
from pwdlib import PasswordHash

router = APIRouter(prefix="/auth", tags=["Authentication"])

BASE_DIR = Path(__file__).resolve().parent
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
IS_PRODUCTION = os.getenv(
    "CONTRIBMATE_ENV", "development"
).lower() == "production"

ALGORITHM = "HS256"
SESSION_DAYS = 7

password_hash = PasswordHash.recommended()

# PostgreSQL on Render, SQLite on localhost.
if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row
else:
    DATA_DIR = Path(
        os.getenv("CONTRIBMATE_DATA_DIR", str(BASE_DIR))
    )
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    DB_PATH = DATA_DIR / "users.db"
    SECRET_FILE = DATA_DIR / ".auth_secret"


def get_secret():
    # Production should always use an environment variable.
    configured = os.getenv("CONTRIBMATE_AUTH_SECRET")
    if configured:
        return configured

    if IS_PRODUCTION:
        raise RuntimeError(
            "CONTRIBMATE_AUTH_SECRET must be set in production."
        )

    if SECRET_FILE.exists():
        return SECRET_FILE.read_text(
            encoding="utf-8"
        ).strip()

    secret = secrets.token_urlsafe(48)

    try:
        with SECRET_FILE.open("x", encoding="utf-8") as file:
            file.write(secret)
    except FileExistsError:
        return SECRET_FILE.read_text(
            encoding="utf-8"
        ).strip()

    return secret


SECRET_KEY = get_secret()


def connect_db():
    if DATABASE_URL:
        return psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10,
        )

    connection = sqlite3.connect(DB_PATH, timeout=15)
    connection.row_factory = sqlite3.Row
    return connection


def initialize_db():
    with connect_db() as db:
        if DATABASE_URL:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                        PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL
                )
            """)
        else:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL
                )
            """)


initialize_db()


class SignupData(BaseModel):
    name: str = Field(min_length=1, max_length=100)
    email: EmailStr
    password: str = Field(min_length=8, max_length=128)


class LoginData(BaseModel):
    email: EmailStr
    password: str


def public_user(user):
    return {
        "id": user["id"],
        "name": user["name"],
        "email": user["email"],
    }


def create_session(response, user_id, request):
    expires = datetime.now(timezone.utc) + timedelta(
        days=SESSION_DAYS
    )

    token = jwt.encode(
        {
            "sub": str(user_id),
            "exp": expires,
        },
        SECRET_KEY,
        algorithm=ALGORITHM,
    )

    response.set_cookie(
        key="contribmate_session",
        value=token,
        httponly=True,
        secure=IS_PRODUCTION or request.url.scheme == "https",
        samesite="none" if IS_PRODUCTION else "lax",
        max_age=SESSION_DAYS * 24 * 60 * 60,
        path="/",
    )


def get_current_user(request):
    token = request.cookies.get("contribmate_session")

    if not token:
        raise HTTPException(
            status_code=401,
            detail="Not logged in.",
        )

    try:
        payload = jwt.decode(
            token,
            SECRET_KEY,
            algorithms=[ALGORITHM],
        )
        user_id = int(payload["sub"])
    except (jwt.InvalidTokenError, ValueError, KeyError):
        raise HTTPException(
            status_code=401,
            detail="Session expired or invalid.",
        )

    with connect_db() as db:
        placeholder = "%s" if DATABASE_URL else "?"

        user = db.execute(
            f"SELECT id, name, email FROM users "
            f"WHERE id = {placeholder}",
            (user_id,),
        ).fetchone()

    if not user:
        raise HTTPException(
            status_code=401,
            detail="User not found.",
        )

    return public_user(user)


@router.post("/signup", status_code=201)
def signup(
    data: SignupData,
    response: Response,
    request: Request,
):
    email = str(data.email).lower().strip()
    name = data.name.strip()

    if not name:
        raise HTTPException(
            status_code=400,
            detail="Name cannot be empty.",
        )

    hashed = password_hash.hash(data.password)

    try:
        with connect_db() as db:
            if DATABASE_URL:
                user = db.execute(
                    """
                    INSERT INTO users
                        (name, email, password_hash)
                    VALUES (%s, %s, %s)
                    RETURNING id
                    """,
                    (name, email, hashed),
                ).fetchone()

                user_id = user["id"]
            else:
                cursor = db.execute(
                    """
                    INSERT INTO users
                        (name, email, password_hash)
                    VALUES (?, ?, ?)
                    """,
                    (name, email, hashed),
                )
                user_id = cursor.lastrowid

    except Exception as exc:
        if DATABASE_URL:
            from psycopg.errors import UniqueViolation

            if isinstance(exc, UniqueViolation):
                raise HTTPException(
                    status_code=409,
                    detail="An account with this email "
                           "already exists.",
                ) from exc
        elif isinstance(exc, sqlite3.IntegrityError):
            raise HTTPException(
                status_code=409,
                detail="An account with this email "
                       "already exists.",
            ) from exc

        raise

    create_session(response, user_id, request)

    return {
        "user": {
            "id": user_id,
            "name": name,
            "email": email,
        }
    }


@router.post("/login")
def login(
    data: LoginData,
    response: Response,
    request: Request,
):
    email = str(data.email).lower().strip()
    placeholder = "%s" if DATABASE_URL else "?"

    with connect_db() as db:
        user = db.execute(
            f"SELECT * FROM users "
            f"WHERE email = {placeholder}",
            (email,),
        ).fetchone()

    if not user or not password_hash.verify(
        data.password,
        user["password_hash"],
    ):
        raise HTTPException(
            status_code=401,
            detail="Invalid email or password.",
        )

    create_session(response, user["id"], request)

    return {"user": public_user(user)}


@router.get("/me")
def me(request: Request):
    return {"user": get_current_user(request)}


@router.post("/logout")
def logout(response: Response):
    response.delete_cookie(
        key="contribmate_session",
        path="/",
        samesite="none" if IS_PRODUCTION else "lax",
        secure=IS_PRODUCTION,
    )

    return {
        "message": "Logged out successfully."
    }
